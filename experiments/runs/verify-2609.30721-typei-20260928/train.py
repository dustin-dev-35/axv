"""
AXV verification of arXiv:2609.30721v1 (Shi, Zhang, Shi; ICTAI 2026).

WHAT IS BEING TESTED
  The paper's operational claim, which is the part AXV acts on:

    (C1) Overlapping test windows are not independent tests. On the fixed-record
         target, IID inference on the paired contrast is anti-conservative under
         dependence, and a session-centred Bartlett-HAC correction substantially
         reduces -- but does not eliminate -- that anti-conservatism.
         (paper: 16.9% -> 7.2% Type-I at 75% overlap, nominal 5%)

    (C2) "Accounting for dependence" is not sufficient; the correction must be aligned
         with the intended highest independent unit. Under subject/session
         heterogeneity, window-level IID and within-session HAC stay severely
         target-misaligned while equal-subject paired inference is near nominal.
         (paper: 72.4% / 66.2% / 5.5%)

    (C3) Overlap multiplies nominal rows faster than independent information.
         (paper: 3.93-3.97x rows -> 1.75-1.94x information at 75% overlap)

WHAT THIS IS, AND IS NOT
  This is NOT a replication. The paper does not release its DGP parameters (subject
  count, session count, raw session duration, AR coefficients, threshold construction),
  so there is no way to reproduce its exact Type-I numbers. What is reimplemented here
  is the *estimator* (paper Eq. 5) plus the paper's stated window geometry (L = 64 raw
  samples, stride 64/32/16 for 0/50/75% overlap) and bandwidth rule
  (K_main = max(K_NW, 2*K0), K0 = ceil(L/S) - 1, c = N/(N-R), Bartlett weights
  1 - h/(K+1), lag products never crossing a session).

  The DGP is therefore OURS, and it is SWEPT over dependence strength rather than tuned
  to reproduce the paper's numbers. Tuning to match would make the test circular. The
  falsifiable prediction is a shape claim, not a point claim:

      P1  IID Type-I error rises monotonically with dependence strength AND with
          overlap; HAC Type-I error stays much closer to nominal across the same
          surface, and the IID-minus-HAC gap is non-negative everywhere.
      P2  Under heterogeneity, IID and HAC are both far above nominal while
          equal-subject paired inference is near nominal.
      P3  G_info(75%) is strictly below the nominal window-growth ratio whenever
          dependence is present, and approaches it when it is not.

DGP
  Stationary Gaussian AR(1) at raw-sample resolution, generated by circulant embedding,
  averaged into overlapping length-L windows (exact window-mean autocovariance used to
  build the window-level process directly -- mathematically identical, far cheaper).
  Per window and model m:
      M = shared window latent   (AR(1) rho_shared)  -> paired, cross-model correlation
      E = model-idiosyncratic    (AR(1) rho_err)     -> error persistence
      C_m = 1{M + E > tau_m},  tau_m set so marginal accuracy = 0.8

COST
  CPU only. No GPU, no RunPod pod, $0.00 of the AXV compute budget. See run.json.
"""

import json
import os
import sys
import time

import numpy as np
from scipy import stats

# ---------------------------------------------------------------- design constants (ours)
L_RAW = 64
N_SUBJ = 30
N_SESS_PER_SUBJ = 2
T_RAW = 6400
MARGINAL = 0.8
ALPHA = 0.05
Z975 = stats.norm.ppf(1 - ALPHA / 2)
STRIDE = {0: 64, 50: 32, 75: 16}
OVERLAPS = (0, 50, 75)
RHOS = (0.0, 0.5, 0.8, 0.95, 0.99)
M = 1000
DRAWS_INFO = 100
SEEDS = (20260928, 20260929, 20260930)
HIER_RHOS = (0.8, 0.95)
SUBJ_SD = 0.30
SESS_SD = 0.20
PAIR_SD = 1.20          # model-pair-level heterogeneity: the component a paired
                        # contrast is actually exposed to

_ACOV_CACHE = {}


# ---------------------------------------------------------------- stationary Gaussian
def window_mean_autocov(rho, L, stride, max_lag):
    """c(d) = (1/L^2) sum_{a,b} rho**|d + b - a| at window-start offset d."""
    d = np.arange(0, max_lag * stride + 1, stride, dtype=np.float64)
    a = np.arange(L, dtype=np.float64)
    lags = d[:, None, None] + a[None, None, :] - a[None, :, None]
    return np.power(rho, np.abs(lags)).mean(axis=(1, 2))


def get_acov(rho, L, stride, n_win):
    key = (rho, L, stride, n_win)
    if key not in _ACOV_CACHE:
        _ACOV_CACHE[key] = window_mean_autocov(rho, L, stride, n_win)
    return _ACOV_CACHE[key]


def stationary_gauss(acov, n_series, n, rng):
    """n_series independent stationary Gaussian series of length n, exact autocovariance."""
    m = min(len(acov), n)
    first_row = np.zeros(n, dtype=np.float64)
    first_row[:m] = acov[:m]
    first_row[n - m + 1:] = acov[1:m][::-1]
    spec = np.sqrt(np.fft.rfft(first_row))
    if np.any(spec <= 0):
        raise RuntimeError("circulant embedding not PSD")
    w = rng.standard_normal((n_series, n))
    return np.fft.irfft(np.fft.rfft(w, axis=-1) * spec, n=n, axis=-1)[:, :n]


def tau_for(sig):
    return stats.norm.ppf(1.0 - MARGINAL) * sig.std()


def make_batch(n_sess, n_win, overlap, rho, subject_sd, session_sd, rng, pair_sd=0.0):
    """
    pair_sd controls MODEL-PAIR-level heterogeneity: a subject/session random effect on
    the A-versus-B difficulty *gap*. The paper's controlled design states dependence at
    "subject, session, raw-sample, and model-pair levels"; the model-pair component is
    what a paired contrast is actually exposed to. A shared-difficulty effect (subject_sd,
    session_sd) shifts both arms together and largely cancels in D = C_A - C_B.
    """
    stride = STRIDE[overlap]
    acov = get_acov(rho, L_RAW, stride, n_win)
    shared = stationary_gauss(acov, n_sess, n_win, rng)
    e_a = stationary_gauss(acov, n_sess, n_win, rng)
    e_b = stationary_gauss(acov, n_sess, n_win, rng)
    if subject_sd > 0:
        off = rng.normal(0.0, subject_sd, size=(n_sess, 1))
        shared = shared + off
        e_a = e_a + off * 0.5
        e_b = e_b + off * 0.5
    if session_sd > 0:
        off = rng.normal(0.0, session_sd, size=(n_sess, 1))
        shared = shared + off
        e_a = e_a + off * 0.5
        e_b = e_b + off * 0.5
    sig_a, sig_b = shared + e_a, shared + e_b
    if pair_sd > 0:
        # asymmetric offset: makes A easier and/or B harder for a whole subject/session
        off_pair = rng.normal(0.0, pair_sd, size=(n_sess, 1))
        sig_a = sig_a + off_pair
    thr_a = stats.norm.ppf(1.0 - MARGINAL) * sig_a.std()
    thr_b = stats.norm.ppf(1.0 - MARGINAL) * sig_b.std()
    C_A = (sig_a > thr_a).astype(np.float64)
    C_B = (sig_b > thr_b).astype(np.float64)
    return C_A, C_B


# ---------------------------------------------------------------- estimators (paper III-C)
def bandwidth(n_win, overlap):
    K0 = int(np.ceil(L_RAW / STRIDE[overlap])) - 1
    K_nw = int(np.floor(4.0 * (n_win / 100.0) ** (2.0 / 9.0)))
    return min(max(K_nw, 2 * K0), n_win - 1), K0, K_nw


def hac_session_centered(D, overlap):
    n_sess, n_win = D.shape
    N = n_sess * n_win
    c = N / (N - n_sess)
    u = D - D.mean(axis=1, keepdims=True)
    K, _, _ = bandwidth(n_win, overlap)
    w = 1.0 - np.arange(1, K + 1) / (K + 1.0)
    acc = np.zeros(n_sess)
    for h in range(1, K + 1):
        acc += w[h - 1] * np.sum(u[:, : n_win - h] * u[:, h:], axis=1)
    var = (c / (N ** 2)) * (float(np.sum(u ** 2)) + 2.0 * float(acc.sum()))
    return float(D.mean()), float(np.sqrt(max(var, 0.0)))


def equal_subject(D, overlap):
    Dsub = D.reshape(N_SUBJ, N_SESS_PER_SUBJ, -1).mean(axis=(1, 2))
    n = Dsub.size
    dbar = float(Dsub.mean())
    var = (n / (n - 1.0)) * float(np.sum((Dsub - dbar) ** 2)) / (n ** 2)
    tcrit = float(stats.t.ppf(1 - ALPHA / 2, n - 1))
    return dbar, float(np.sqrt(max(var, 0.0))), tcrit


# ---------------------------------------------------------------- Monte Carlo
def run_condition(overlap, rho, seed, subject_sd=0.0, session_sd=0.0, M=M, pair_sd=0.0):
    n_win = (T_RAW - L_RAW) // STRIDE[overlap] + 1
    n_sess = N_SUBJ * N_SESS_PER_SUBJ
    rng = np.random.default_rng(int((seed * 7919 + rho * 1000 + overlap * 10) % (2 ** 31)))
    rej = np.zeros(3, dtype=np.int64)
    for _ in range(M):
        C_A, C_B = make_batch(
            n_sess, n_win, overlap, rho, subject_sd, session_sd, rng, pair_sd=pair_sd
        )
        D = C_A - C_B
        dbar = float(D.mean())
        se_iid = float(D.std(ddof=1)) / np.sqrt(D.size)
        if abs(dbar) > Z975 * se_iid:
            rej[0] += 1
        _, se_h = hac_session_centered(D, overlap)
        if abs(dbar) > Z975 * se_h:
            rej[1] += 1
        dbar_s, se_s, tcrit = equal_subject(D, overlap)
        if abs(dbar_s) > tcrit * se_s:
            rej[2] += 1
    out = dict(
        overlap=overlap, rho=rho, seed=seed, M=M,
        subject_sd=subject_sd, session_sd=session_sd, pair_sd=pair_sd,
        n_win=n_win, N=n_win * n_sess, n_subj=N_SUBJ, n_sess=n_sess,
        K_used=bandwidth(n_win, overlap)[0],
        K0=bandwidth(n_win, overlap)[1],
    )
    for i, name in enumerate(("iid", "hac", "subj")):
        p = rej[i] / M
        out[name] = float(p)
        out[name + "_mcse"] = float(np.sqrt(max(p * (1 - p), 0.0) / M))
    return out


def information_growth(rho, seed, draws=DRAWS_INFO):
    n_sess = N_SUBJ * N_SESS_PER_SUBJ
    rng = np.random.default_rng(int((seed * 104729 + rho * 101) % (2 ** 31)))
    var = {}
    for ov in OVERLAPS:
        n_win = (T_RAW - L_RAW) // STRIDE[ov] + 1
        acc = []
        for _ in range(draws):
            C_A, C_B = make_batch(n_sess, n_win, ov, rho, 0.0, 0.0, rng)
            D = C_A - C_B
            acc.append(hac_session_centered(D, ov)[1] ** 2)
        var[ov] = float(np.mean(acc))
    n0 = (T_RAW - L_RAW) // STRIDE[0] + 1
    n75 = (T_RAW - L_RAW) // STRIDE[75] + 1
    return dict(
        rho=rho, seed=seed, draws=draws, var_dep=var,
        window_growth_50=n50_to(n0), window_growth_75=n75 / n0,
        G_info_50=var[0] / var[50], G_info_75=var[0] / var[75],
    )


def n50_to(n0):
    return ((T_RAW - L_RAW) // STRIDE[50] + 1) / n0


def main():
    t0 = time.time()
    res = {"calibration": [], "hierarchical": [], "hierarchical_shared": [], "information": []}

    for rho in RHOS:
        for ov in OVERLAPS:
            for seed in SEEDS:
                r = run_condition(ov, rho, seed)
                res["calibration"].append(r)
                print(f"sweep rho={rho:<5} ov={ov:<2} seed={seed} "
                      f"IID={r['iid']:.3f} HAC={r['hac']:.3f} SUBJ={r['subj']:.3f} "
                      f"K={r['K_used']} N={r['N']}", flush=True)

    for rho in HIER_RHOS:
        for ov in OVERLAPS:
            for seed in SEEDS:
                # shared-difficulty heterogeneity only: largely cancels in the paired
                # difference, so this is the control arm
                r = run_condition(ov, rho, seed, SUBJ_SD, SESS_SD, pair_sd=0.0)
                r["arm"] = "shared_only"
                res["hierarchical_shared"].append(r)
                print(f"hier-shared rho={rho:<5} ov={ov:<2} seed={seed} "
                      f"IID={r['iid']:.3f} HAC={r['hac']:.3f} SUBJ={r['subj']:.3f}", flush=True)
                # + model-pair-level heterogeneity: the component a paired contrast
                # is actually exposed to
                r2 = run_condition(ov, rho, seed, SUBJ_SD, SESS_SD, pair_sd=PAIR_SD)
                r2["arm"] = "shared_plus_pair"
                res["hierarchical"].append(r2)
                print(f"hier-pair   rho={rho:<5} ov={ov:<2} seed={seed} "
                      f"IID={r2['iid']:.3f} HAC={r2['hac']:.3f} SUBJ={r2['subj']:.3f}", flush=True)

    for rho in RHOS:
        for seed in SEEDS:
            g = information_growth(rho, seed)
            res["information"].append(g)
            print(f"info  rho={rho:<5} seed={seed} "
                  f"rows_75={g['window_growth_75']:.2f}x G_info_75={g['G_info_75']:.2f}x",
                  flush=True)

    res["aggregate"] = aggregate(res["calibration"] + res["hierarchical"] + res["hierarchical_shared"])
    res["aggregate_info"] = aggregate(res["information"], keys=("window_growth_50", "window_growth_75", "G_info_50", "G_info_75"), by="rho")
    res["predictions"] = check_predictions(res)
    res["meta"] = {
        "generated_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "wall_seconds": round(time.time() - t0, 1),
        "seeds": list(SEEDS),
        "M_per_condition": M,
        "draws_info": DRAWS_INFO,
        "design": {
            "L_raw": L_RAW, "T_raw_per_session": T_RAW,
            "n_subjects": N_SUBJ, "n_sessions_per_subject": N_SESS_PER_SUBJ,
            "marginal_null_accuracy": MARGINAL, "alpha": ALPHA,
            "subject_sd": SUBJ_SD, "session_sd": SESS_SD, "pair_sd": PAIR_SD,
            "rhos": list(RHOS), "hier_rhos": list(HIER_RHOS),
            "overlaps": list(OVERLAPS),
        },
        "numpy": np.__version__, "python": sys.version.split()[0],
        "compute": "CPU only. No GPU, no RunPod pod. $0.00 of the AXV compute budget.",
        "not_a_replication": (
            "The paper does not release its DGP parameters. The estimator (Eq. 5), "
            "window geometry and bandwidth rule are the paper's; the DGP is ours and is "
            "swept over dependence strength rather than tuned to match the paper's "
            "Type-I numbers. This is a shape test of P1-P3, not a point replication."
        ),
    }
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "metrics.json")
    with open(out, "w", encoding="utf-8") as fh:
        json.dump(res, fh, indent=2)
    print("wrote", out)
    print("wall_seconds", res["meta"]["wall_seconds"])
    for k, v in res["predictions"].items():
        if "holds" in v:
            print(f"  {k}: {'HOLDS' if v['holds'] else 'FAILS'}  {v['detail']}")
        else:
            print(f"  {k}: (report)")


def aggregate(rows, keys=None, by="rho"):
    agg = {}
    groups = {}
    for r in rows:
        key = (r[by], r.get("overlap"), r.get("arm", "main"))
        groups.setdefault(key, []).append(r)
    for (rho, ov, arm), rs in groups.items():
        tag = f"rho={rho}" + (f",ov={ov}" if ov is not None else "") + (f",{arm}" if arm != "main" else "")
        kk = keys or ("iid", "hac", "subj")
        for m in kk:
            if m not in rs[0]:
                continue
            vals = [r[m] for r in rs]
            agg[f"{tag},{m}"] = {
                "mean": float(np.mean(vals)), "min": float(np.min(vals)),
                "max": float(np.max(vals)), "spread": float(np.max(vals) - np.min(vals)),
                "per_seed": [float(v) for v in vals],
                "mcse_mean": float(np.mean([r[m + "_mcse"] for r in rs])) if (m + "_mcse") in rs[0] else None,
            }
    return agg


def check_predictions(res):
    out = {}

    # P1a / P1b: seed-averaged surface, ordered by overlap 0 / 50 / 75
    def by_overlap(rho, m):
        return [
            float(np.mean([
                r[m] for r in res["calibration"]
                if r["rho"] == rho and r["overlap"] == ov
            ]))
            for ov in OVERLAPS
        ]

    ok_iid, ok_hac_gap, table = [], [], []
    for rho in RHOS:
        a = by_overlap(rho, "iid")
        b = by_overlap(rho, "hac")
        table.append({"rho": rho, "iid": [round(x, 4) for x in a],
                      "hac": [round(x, 4) for x in b],
                      "gap": [round(x - y, 4) for x, y in zip(a, b)]})
        if a[2] > a[0]:
            ok_iid.append(rho)
        if all(x - y >= -0.005 for x, y in zip(a, b)):
            ok_hac_gap.append(rho)
    out["surface_iid_vs_hac"] = {
        "note": "Type-I error, mean over 3 seeds; entries are overlap 0/50/75; nominal 0.05",
        "rows": table,
    }
    out["P1a_iid_inflates_with_overlap"] = {
        "holds": len(ok_iid) == len(RHOS),
        "detail": f"IID(75%) > IID(0%) at rho in {ok_iid} of {list(RHOS)}",
    }
    out["P1b_hac_gap_nonnegative"] = {
        "holds": len(ok_hac_gap) == len(RHOS),
        "detail": f"IID-HAC >= 0 at every overlap for rho in {ok_hac_gap} of {list(RHOS)}",
    }

    # P1c: HAC materially below IID at 75% overlap under real dependence
    strong = [r for r in res["calibration"] if r["overlap"] == 75 and r["rho"] >= 0.8]
    gap75 = float(np.mean([r["iid"] - r["hac"] for r in strong]))
    out["P1c_hac_substantially_below_iid_at_75"] = {
        "holds": gap75 >= 0.03,
        "detail": f"mean(IID-HAC) at 75% overlap, rho>=0.8: {gap75:.4f} (threshold 0.03)",
    }

    # P2: under model-pair-level heterogeneity, subj near nominal, iid and hac far above
    sub = [r["subj"] for r in res["hierarchical"]]
    iid = [r["iid"] for r in res["hierarchical"]]
    hac = [r["hac"] for r in res["hierarchical"]]
    out["P2_target_alignment"] = {
        "holds": (float(np.mean(sub)) <= 0.10
                  and float(np.mean(iid)) > 3 * float(np.mean(sub))
                  and float(np.mean(hac)) > 3 * float(np.mean(sub))),
        "detail": (f"shared+pair heterogeneity: IID={np.mean(iid):.3f} "
                   f"HAC={np.mean(hac):.3f} SUBJ={np.mean(sub):.3f}  "
                   f"(needs SUBJ<=0.10 and IID,HAC > 3x SUBJ)"),
    }

    # P2b (structural): shared-difficulty heterogeneity alone largely cancels in the
    # paired difference, so window-level IID is NOT badly anti-conservative without a
    # model-pair-level component. This is the AXV-relevant refinement of the paper's P2.
    s_iid = [r["iid"] for r in res["hierarchical_shared"]]
    s_hac = [r["hac"] for r in res["hierarchical_shared"]]
    s_sub = [r["subj"] for r in res["hierarchical_shared"]]
    out["P2b_shared_difficulty_cancels_in_paired_contrast"] = {
        "holds": float(np.mean(s_iid)) <= 0.12,
        "detail": (f"shared-difficulty only: IID={np.mean(s_iid):.3f} "
                   f"HAC={np.mean(s_hac):.3f} SUBJ={np.mean(s_sub):.3f}; "
                   f"compare shared+pair IID={np.mean(iid):.3f}. "
                   f"A shared difficulty shift moves both arms together and cancels "
                   f"in C_A - C_B; only the model-pair component breaks target alignment."),
    }

    # P3: G_info(75) below nominal window growth when dependence present
    rows75 = [g for g in res["information"] if g["rho"] >= 0.5]
    ok = []
    for g in rows75:
        ok.append(g["G_info_75"] < g["window_growth_75"])
    out["P3_info_growth_below_row_growth"] = {
        "holds": all(ok) and len(ok) > 0,
        "detail": "; ".join(f"rho={g['rho']} G_info_75={g['G_info_75']:.2f} vs rows {g['window_growth_75']:.2f}"
                            for g in rows75),
    }
    # P3b: decompose the information shortfall into mechanical overlap vs persistence
    def g75(rho):
        vals = [g["G_info_75"] for g in res["information"] if g["rho"] == rho]
        return float(np.mean(vals)) if vals else float("nan")

    rows_growth = float(np.mean([g["window_growth_75"] for g in res["information"]]))
    out["P3b_information_shortfall_decomposition"] = {
        "holds": g75(0.0) < rows_growth,
        "detail": (
            f"nominal row growth at 75% overlap = {rows_growth:.2f}x. "
            f"Information growth: rho=0 (mechanical overlap only) {g75(0.0):.2f}x "
            f"({rows_growth / g75(0.0):.2f}x of nominal); "
            f"rho=0.8 {g75(0.8):.2f}x; rho=0.95 {g75(0.95):.2f}x; rho=0.99 {g75(0.99):.2f}x. "
            f"Mechanical overlap alone costs {rows_growth / g75(0.0) - 1:.0%} of the "
            f"nominal information; AR(1) persistence adds a further "
            f"{g75(0.0) / g75(0.99) - 1:.0%}."
        ),
    }
    return out


if __name__ == "__main__":
    main()
